import assert from 'node:assert/strict';
import {createEngine} from './engine.mjs';
const e=createEngine();
assert.ok((r=>r.lines.some(l=>l.text.includes("rabbit")))(e.run("help")),"help");
assert.ok((r=>r.lines.length===3&&r.lines.every(l=>l.url.startsWith("https://github.com/")))(e.run("projects")),"projects");
assert.ok((r=>r.lines[0].text.includes("Adalberto"))(e.run("cat about.txt")),"cat about.txt");
assert.ok((r=>r.lines[0].kind==="error")(e.run("cat __proto__")),"cat __proto__");
assert.ok((r=>r.lines[0].kind==="error")(e.run("constructor")),"constructor");
assert.ok((r=>r.lines[0].text==="white rabbit")(e.run("decode d2hpdGUgcmFiYml0")),"decode d2hpdGUgcmFiYml0");
assert.ok((r=>r.lines[0].text==="a")(e.run("decode YQ==")),"decode YQ==");
assert.ok((r=>r.lines[0].kind==="error")(e.run("decode !!!")),"decode !!!");
assert.ok((r=>r.lines[0].kind==="error")(e.run("decode a")),"decode a");
assert.ok((r=>r.lines[0].kind==="error")(e.run("answer wrong")),"answer wrong");
assert.ok((r=>r.lines[0].text.includes("ACCESS GRANTED"))(e.run("answer White Rabbit")),"answer White Rabbit");
assert.ok((r=>r.lines[0].text.includes("COMPLETO"))(e.run("rabbit")),"rabbit");
assert.ok((r=>r.lines[0].text.includes("reiniciado"))(e.run("reset")),"reset");
assert.ok((r=>r.lines[0].text.includes("ENCODING"))(e.run("rabbit")),"rabbit");
assert.ok((r=>r.lines[0].text==="<img src=x>")(e.run("echo <img src=x>")),"echo <img src=x>");
assert.ok((r=>r.clear===true)(e.run("clear")),"clear");
assert.ok((r=>r.lines.length===0)(e.run("")),"empty");
console.log('17 testes passaram.');
